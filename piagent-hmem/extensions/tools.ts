// ── Stats ────────────────────────────────────────────────────────

export async function handleStats(
	client: HmemClient,
	args: Record<string, unknown>,
): Promise<string> {
	const result = await client.stats(args.namespace as string | undefined);
	if (!result.ok) return `❌ ${result.error}`;
	const s = result.data!;
	const byType = Object.entries(s.by_type ?? {})
		.map(([k, v]) => `  ${k}: ${v}`)
		.join("\n");

	return [
		`📊 HMEM Memory Stats — namespace: \`${s.namespace}\``,
		`  Total: ${s.total_memories}`,
		`  Embeddings: ${s.embedding_enabled ? "✅ ON" : "❌ OFF"}`,
		byType ? `\nBy type:\n${byType}` : "",
	]
		.filter(Boolean)
		.join("\n");
}

