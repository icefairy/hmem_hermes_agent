/**
 * HMEM tool implementations — each tool is a standalone async function
 * that receives the HmemClient and tool parameters, and returns a
 * tool-call result string.
 */

import type { HmemClient } from "./client.ts";

// ── Helpers ──────────────────────────────────────────────────────

function json(data: unknown): string {
	return JSON.stringify(data, null, 2);
}

function truncate(s: string, max = 300): string {
	if (s.length <= max) return s;
	return s.slice(0, max) + "...";
}

// ── Write ────────────────────────────────────────────────────────

export async function handleWrite(
	client: HmemClient,
	args: Record<string, unknown>,
): Promise<string> {
	const content = args.content as string | undefined;
	if (!content) return "❌ `content` is required";

	const memoryType = (args.memory_type as string) || "observation";
	if (memoryType === "insight" || memoryType === "mental_model") {
		return `❌ Cannot write type "${memoryType}" directly. Insights and mental models are only generated by the reflection engine (hmem_reflect). Use: observation or experience.`;
	}

	const result = await client.writeMemory({
		content,
		memory_type: memoryType,
		mem_action: (args.mem_action as string) || "",
		mem_context: (args.mem_context as Record<string, unknown>) || {},
		mem_outcome: (args.mem_outcome as Record<string, unknown>) || {},
		mem_metadata: (args.mem_metadata as Record<string, unknown>) || {},
		namespace: args.namespace as string | undefined,
	});

	if (!result.ok) return `❌ ${result.error}`;
	return json({
		memory_id: result.data!.memory_id,
		content: truncate(result.data!.content, 100),
		namespace: result.data!.namespace,
		embedded: result.data!.embedded,
		auto_reflected: result.data!.auto_reflected,
	});
}

// ── Search ───────────────────────────────────────────────────────

export async function handleSearch(
	client: HmemClient,
	args: Record<string, unknown>,
): Promise<string> {
	const query = args.query as string | undefined;
	if (!query) return "❌ `query` is required";

	const result = await client.search({
		query,
		limit: Math.min((args.limit as number) || 10, 50),
		use_rerank: args.use_rerank !== false,
		min_score: args.min_score as number | undefined,
		namespace: args.namespace as string | undefined,
	});

	if (!result.ok) return `❌ ${result.error}`;
	const items = result.data!.results;
	if (items.length === 0) return "📭 No relevant memories found.";

	const lines = items.map((m, i) => {
		const score = m.score === undefined ? "" : `[${m.score.toFixed(2)}]`;
		const type = m.memory_type ? `(${m.memory_type})` : "";
		const id = m.id ? `#${m.id}` : "";
		const src = m.source
			? ` 📄${m.source.title || m.source.doc_id}#${m.source.chunk_index ?? 0}`
			: "";
		return `${i + 1}. ${score} ${type} ${id} ${truncate(m.content, 200)}${src}`;
	});

	return `📚 Found ${items.length} memories:\n\n${lines.join("\n")}`;
}

// ── List ─────────────────────────────────────────────────────────

export async function handleList(
	client: HmemClient,
	args: Record<string, unknown>,
): Promise<string> {
	const result = await client.listMemories({
		namespace: args.namespace as string | undefined,
		limit: Math.min((args.limit as number) || 20, 100),
		memory_type: args.memory_type as string | undefined,
	});

	if (!result.ok) return `❌ ${result.error}`;
	const items = result.data!.results;
	if (items.length === 0) return "📭 No memories.";

	const lines = items.map((m) => {
		const type = m.memory_type ?? "observation";
		const id = m.id ?? "?";
		const date = m.created_at ? m.created_at.slice(0, 19) : "";
		const doc = m.doc_title ? ` [📄${m.doc_title}#${m.chunk_index ?? 0}]` : "";
		return `  #${id} [${type}] ${date}${doc}  ${truncate(m.content, 120)}`;
	});

	return `📖 ${items.length} memories:\n${lines.join("\n")}`;
}

// ── Get single ───────────────────────────────────────────────────

